async function parentBuildReply(event) {
  const { requestId } = event.data;
  let opened = null;
  let openedReason = "document-unavailable";
  try {
    await graphWrites;
    const state = await graphState();
    if (event.source?.id && appDocument(event.source)) {
      // Read the same lease used by fetch, including a late old navigation,
      // without creating/updating that lease just to display Parent information.
      opened = state.clients[event.source.id] || state.previous || CACHE_VERSION;
      openedReason = "reported";
    }
  } catch (_) { openedReason = "lease-unavailable"; }
  event.ports[0].postMessage({ type: "RV_BUILD", v: 1, requestId,
    opened, active: CACHE_VERSION, openedReason });
}

self.addEventListener("message", (event) => {
  const data = event.data;
  const type = typeof data === "string" ? data : data && data.type;
  if (type === "RV_BUILD") {
    if (data.v === 1 && typeof data.requestId === "string" && /^[a-z0-9-]{1,96}$/.test(data.requestId)
      && typeof event.ports?.[0]?.postMessage === "function") {
      event.waitUntil(parentBuildReply(event).catch(() => {}));
    }
    return;
  }
  if (type === "SKIP_WAITING") self.skipWaiting();
  if (type === "RV_VERSION" && data?.version !== undefined) {
    if (previousVersionRequest && event.source === previousVersionRequest.worker) {
      previousVersionRequest.accept(data.version);
    }
    return;
  }
  if (type === "RV_VERSION" && event.source) {
    event.source.postMessage({ type: "RV_VERSION", version: CACHE_VERSION });
  }
});

// -------------------------------------------------------------- runtime LRU

/* The Cache API returns keys() in insertion order, so "touch on hit" (delete then
 * re-put) is a real LRU with no extra bookkeeping store to keep in sync. */
async function touch(cache, request, response) {
  try {
    await cache.delete(request);
    await cache.put(request, response.clone());
  } catch (_) {}
}

async function trimRuntime(cache) {
  try {
    const keys = await cache.keys();
    const over = keys.length - RUNTIME_MAX;
    for (let i = 0; i < over; i++) await cache.delete(keys[i]); // oldest first
  } catch (_) {}
}

async function runtimeFirst(request, clientId = "") {
  // A file that made it into the build's precache list wins: it is already offline
  // safe and must never be re-fetched (or evicted) through the runtime LRU.
  const version = await documentVersion(clientId);
  const pinned = await caches.match(request, { cacheName: `rv-precache-${version}` });
  if (pinned) return pinned;

  const cache = await caches.open(`rv-runtime-${version}`);
  const hit = await cache.match(request);
  if (hit) {
    touch(cache, request, hit); // fire and forget: do not delay the response
    return hit;
  }
  if (version !== CACHE_VERSION) throw new Error("previous document graph unavailable");
  const res = await fetch(request);
  if (res && res.ok && res.status === 200) {
    await cache.put(request, res.clone());
    await trimRuntime(cache);
  }
  return res;
}

