// Lazily cached on first use: big, optional, and not needed to boot.
const RUNTIME_PREFIXES = ["assets/voices/", "assets/art/"];
const BLOCKED_PARTS = ["/.git/", "/.claude/", "/backups/", "/references/", "/lane-files/", "/rollouts/", "/assets/art/generated/"];

const SCOPE_PATH = new URL("./", self.location).pathname;
const GRAPH_STATE_URL = new URL("./.rv-worker-graphs", self.location).href;
let graphStatePromise = null;
let graphWrites = Promise.resolve();
let previousVersionRequest = null;

function relPath(url) {
  // "/rainbow/assets/art/x.png" -> "assets/art/x.png" (scope relative)
  const p = new URL(url).pathname;
  return p.startsWith(SCOPE_PATH) ? p.slice(SCOPE_PATH.length) : p.replace(/^\//, "");
}

function isRuntimeAsset(url) {
  const rel = relPath(url);
  return RUNTIME_PREFIXES.some((pre) => rel.startsWith(pre));
}

function isSelf(url) {
  return relPath(url) === "sw.js"; // a worker never caches itself
}

function isBlocked(url) {
  const path = new URL(url).pathname.toLowerCase();
  return BLOCKED_PARTS.some((part) => path.includes(part));
}

