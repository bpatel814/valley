async function cacheFirst(request, clientId = "") {
  const version = await documentVersion(clientId);
  const name = `rv-precache-${version}`;
  const url = new URL(request.url);
  const revision = url.searchParams.get("v");
  const code = /\.(?:js|css)$/.test(url.pathname);
  const hit = await caches.match(request, { cacheName: name });
  if (hit) {
    if (version !== CACHE_VERSION && revision && code && await responseRevision(hit) !== revision) {
      throw new Error("module revision unavailable");
    }
    return hit;
  }
  // A retained shell must never repair a missing dependency with the mutable
  // server's newer unversioned bytes, or borrow a complete waiting/newer graph.
  if (version !== CACHE_VERSION) throw new Error("previous document graph unavailable");
  const declared = PRECACHE_REVISIONS[`./${relPath(url.href)}`];
  if (code && revision && declared && revision !== declared) throw new Error("module revision unavailable");
  const res = await fetch(request);
  if (res && res.ok && res.status === 200 && request.method === "GET") {
    if (revision && code && await responseRevision(res) !== revision) {
      // The server may only retain its newest files. Never label those bytes as
      // an older requested module, or silently substitute another build offline.
      throw new Error("module revision unavailable");
    }
    await (await caches.open(PRECACHE_NAME)).put(request, res.clone());
  }
  return res;
}

async function handleNavigate(request, resultingClientId = "") {
  // The active worker owns a coherent shell and complete dependency graph.
  // A new shell appears only after the existing pen-safe activation handshake.
  const pre = await caches.open(PRECACHE_NAME);
  const path = relPath(request.url);
  // Permanent same-origin child entry points. Ignore incoming world/query/hash:
  // the name in the shared link always selects its own fixed saved world.
  const child = /^(rayna|veer)(?:\/|\/index\.html)?$/.exec(path)?.[1];
  if (child) return Response.redirect(new URL(`./?world=${child}`, self.location).href, 302);
  if (!path || path === "index.html" || path === "demo.html") {
    // A demo navigation must never fall back to the family document.
    const documentPath = path === "demo.html" ? "./demo.html" : "./index.html";
    const index = await pre.match(new URL(documentPath, self.location).href);
    if (index) {
      await bindDocument(resultingClientId, CACHE_VERSION);
      return index;
    }
  }
  try {
    const res = await fetch(request);
    if (res && res.ok) return res;
  } catch (_) {}
  return new Response("", { status: 504, statusText: "offline" });
}

