function versionedCodeURL(path, revision) {
  if (!/\.(?:js|css)$/.test(new URL(path, self.location).pathname)) return null;
  const url = new URL(path, self.location);
  url.searchParams.set("v", revision);
  return url.href;
}

async function responseRevision(response) {
  const bytes = await response.clone().arrayBuffer();
  const hash = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(hash), (byte) => byte.toString(16).padStart(2, "0")).join("").slice(0, 12);
}

// A document can still be opening the previous shell when another tab safely
// activates an update. Keep that document's entire graph, not just a collection
// of old module aliases. This small lease record lives beside the verified graph
// and survives the browser stopping/restarting the worker between fetch events.
function validVersion(version) {
  return typeof version === "string" && (version === CACHE_VERSION || /^[a-f0-9]{12}$/.test(version));
}

function appDocument(client) {
  if (!client?.url) return false;
  const url = new URL(client.url);
  return url.origin === self.location.origin && (!relPath(url.href) || ["index.html", "demo.html"].includes(relPath(url.href)));
}

async function readGraphState(name = PRECACHE_NAME) {
  const response = await caches.match(GRAPH_STATE_URL, { cacheName: name });
  if (!response) return null; // the previous worker may predate graph leases
  const state = await response.json();
  if (state?.v !== 1 || !Array.isArray(state.graphs) || !state.graphs.every(validVersion)
    || (state.previous !== null && !validVersion(state.previous))
    || !state.clients || Array.isArray(state.clients) || typeof state.clients !== "object"
    || !Object.values(state.clients).every(version => state.graphs.includes(version))) {
    throw new Error("worker graph lease unavailable");
  }
  return state;
}

function graphState() {
  if (!graphStatePromise) graphStatePromise = readGraphState().then(state => state || {
    v: 1, previous: null, graphs: [CACHE_VERSION], clients: {},
  });
  return graphStatePromise;
}

async function writeGraphState(state) {
  const cache = await caches.open(PRECACHE_NAME);
  await cache.put(GRAPH_STATE_URL, new Response(JSON.stringify(state), {
    headers: { "Content-Type": "application/json" },
  }));
  graphStatePromise = Promise.resolve(state);
}

function bindDocument(id, version) {
  if (!id) return Promise.resolve();
  const operation = graphWrites.then(async () => {
    const state = await graphState();
    if (state.clients[id] === version) return;
    const next = { ...state, clients: { ...state.clients, [id]: version },
      graphs: [...new Set([...state.graphs, version])] };
    await writeGraphState(next);
  });
  graphWrites = operation.catch(() => {});
  return operation;
}

async function documentVersion(id) {
  const state = await graphState();
  if (id && state.clients[id]) return state.clients[id];
  // A navigation already answered by the retired worker can create its document
  // after activate's client snapshot. New navigations are explicitly bound below.
  if (id && state.previous && appDocument(await self.clients.get(id))) {
    await bindDocument(id, state.previous);
    return state.previous;
  }
  return CACHE_VERSION;
}

function previousActiveVersion() {
  const worker = self.registration.active;
  if (!worker) return Promise.resolve(null);
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => {
      previousVersionRequest = null;
      reject(new Error("previous worker version unavailable"));
    }, 5000);
    previousVersionRequest = { worker, accept(version) {
      clearTimeout(timer);
      previousVersionRequest = null;
      if (!/^[a-f0-9]{12}$/.test(version) || version === CACHE_VERSION) {
        reject(new Error("previous worker version unavailable"));
      } else resolve(version);
    } };
    try { worker.postMessage({ type: "RV_VERSION" }); }
    catch (_) {
      clearTimeout(timer);
      previousVersionRequest = null;
      reject(new Error("previous worker version unavailable"));
    }
  });
}

// An update must not make a phone download all 200+ MB again. A file whose bytes
// an earlier build already verified (same revision hash) is copied from that
// build's cache; only changed or new files touch the network. The bytes are
// re-hashed here, so a damaged old entry is simply fetched again.
async function earlierCopy(path, revision, names) {
  for (const name of names) {
    try {
      const hit = await caches.match(path, { cacheName: name });
      if (hit?.ok && await responseRevision(hit) === revision) return hit;
    } catch (_) {}
  }
  return null;
}

// One dropped request on home wifi must not throw away a 1,300-file install.
async function fetchWithRetry(path, tries = 3) {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(new Request(path, { cache: "reload" }));
      if (res?.ok || attempt >= tries || (res && res.status < 500 && res.status !== 408 && res.status !== 429)) return res;
    } catch (error) {
      if (attempt >= tries) throw error;
    }
    await new Promise((resolve) => setTimeout(resolve, 400 * attempt));
  }
}

async function cacheDeclared(cache, paths, concurrency = 6) {
  const missing = [];
  let cursor = 0;
  let earlier = [];
  try {
    const rank = (n) => (n.startsWith("rv-precache-") ? 0 : 1);
    earlier = (await caches.keys())
      .filter((n) => n !== PRECACHE_NAME && /^rv-(?:precache|runtime)-/.test(n))
      .sort((a, b) => rank(a) - rank(b));
  } catch (_) {}
  async function worker() {
    while (cursor < paths.length) {
      const path = paths[cursor++];
      try {
        const revision = PRECACHE_REVISIONS[path];
        const reused = revision && earlier.length ? await earlierCopy(path, revision, earlier) : null;
        const res = reused || await fetchWithRetry(path);
        if (!res?.ok || !revision || (!reused && await responseRevision(res) !== revision)) {
          missing.push(path);
          continue;
        }
        // Same-version hashed imports must work before ever visiting that screen.
        // Verify bytes so a deployment changed during install cannot form a mixed cache.
        const alias = versionedCodeURL(path, revision);
        if (alias) await cache.put(alias, res.clone());
        await cache.put(path, res);
      } catch (_) {
        missing.push(path);
      }
    }
  }
  const count = Math.min(concurrency, Math.max(1, paths.length));
  await Promise.all(Array.from({ length: count }, worker));
  return missing;
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(PRECACHE_NAME);
      // Fetch independently so one response does not cancel useful diagnostics,
      // but reject the install if even one declared file is absent. Activating a
      // partial cache can produce an offline page whose module graph cannot boot.
      // Six workers keep a large offline install moving without flooding the
      // browser/server and starving the child's first route navigation.
      try {
        const previous = await previousActiveVersion();
        // Old offline files are disposable, unlike family saves. A missing or
        // damaged old cache must not prevent a fully verified replacement from
        // installing. Keep the old version identity so existing documents still
        // fail closed rather than borrowing this build's modules.
        // Never read, migrate or clear IndexedDB/localStorage here.
        const missing = await cacheDeclared(cache, PRECACHE, 6);
        if (missing.length) throw new Error(`precache incomplete: ${missing.length} file(s)`);
        await writeGraphState({ v: 1, previous, graphs: [CACHE_VERSION], clients: {} });
      } catch (error) {
        await caches.delete(PRECACHE_NAME);
        throw error;
      }
      // Updates wait until js/pwa.js finds a safe point between drawing turns.
    })()
  );
});

// ---------------------------------------------------------------- activate

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const installed = await graphState();
      const previous = installed.previous;
      let prior = null;
      if (previous) {
        try { prior = await readGraphState(`rv-precache-${previous}`); }
        catch (_) { /* Damaged lease metadata cannot block a verified update. */ }
      }
      const clients = {};
      // During activate, existing windows need not yet report this new worker
      // as their controller. Uncontrolled windows stay uncontrolled on updates.
      const open = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
      for (const client of open) {
        if (appDocument(client)) clients[client.id] = prior?.clients[client.id] || previous || CACHE_VERSION;
      }
      // Keep a known initializing document even if matchAll hasn't returned it
      // yet; get() can resolve its pending execution-ready client separately.
      for (const [id, version] of Object.entries(prior?.clients || {})) {
        if (!clients[id] && appDocument(await self.clients.get(id))) clients[id] = version;
      }
      const graphs = [...new Set([CACHE_VERSION, previous, ...Object.values(clients)].filter(Boolean))];
      const keep = new Set(graphs.flatMap(version => [`rv-precache-${version}`, `rv-runtime-${version}`]));
      const names = await caches.keys();
      // Missing old graphs remain pinned for existing documents; dependency
      // requests fail closed until those documents reopen. Do not make cache
      // damage a permanent update deadlock. New navigations use this verified
      // graph. Retain all known old graphs that still exist for rollback.
      await writeGraphState({ v: 1, previous, graphs, clients });
      await Promise.all(
        names.filter((n) => n.startsWith("rv-") && !keep.has(n)).map((n) => caches.delete(n))
      );
      if (self.registration.navigationPreload) {
        try { await self.registration.navigationPreload.disable(); } catch (_) {}
      }
      // skipWaiting changes existing controlled documents. Claiming an unrelated
      // uncontrolled tab too could attach an older graph to newer network HTML.
      if (!previous) await self.clients.claim();
    })()
  );
});

