self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // the app makes no cross-origin calls
  if (isSelf(url.href)) return; // let the browser's own update check own sw.js
  if (url.pathname === new URL(GRAPH_STATE_URL).pathname) {
    event.respondWith(new Response("not found", { status: 404 }));
    return;
  }
  if (isBlocked(url.href)) {
    event.respondWith(new Response("not found", { status: 404, statusText: "not found" }));
    return;
  }

  if (req.mode === "navigate") {
    event.respondWith(handleNavigate(req, event.resultingClientId || event.clientId).catch(() => navigationRecovery()));
    return;
  }
  if (isRuntimeAsset(url.href)) {
    event.respondWith(
      runtimeFirst(req, event.clientId).catch(() => new Response("", { status: 504, statusText: "offline" }))
    );
    return;
  }
  event.respondWith(
    cacheFirst(req, event.clientId).catch(() => new Response("", { status: 504, statusText: "offline" }))
  );
});
